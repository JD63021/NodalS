template<int WARPS,bool COMPUTE_FLOAT,bool ACCUM_FLOAT>
__global__ void h7_supg64_r2_kernel(
    const G4CellPlanDevice* __restrict__ cells,int nc,
    const std::int64_t* __restrict__ row,
    const StateReal* __restrict__ fixed,
    const StateReal* __restrict__ u0,
    const StateReal* __restrict__ u1,
    const StateReal* __restrict__ u2,
    OperatorReal nuIn,OperatorReal tauScaleIn,OperatorReal supgMagicIn,
    OperatorReal* __restrict__ aval,
    StateReal* __restrict__ cr0,
    StateReal* __restrict__ cr1,
    StateReal* __restrict__ cr2)
{
  using C = typename std::conditional<COMPUTE_FLOAT,float,OperatorReal>::type;
  using A = typename std::conditional<ACCUM_FLOAT,float,OperatorReal>::type;

  const int tid=(int)threadIdx.x;
  const int lane=tid&31;
  const int warp=tid>>5;

  __shared__ C sCoeff[8][3];
  __shared__ C sGL[4][3];
  __shared__ C sGram[4][4];
  __shared__ A sPart[WARPS][64];
  __shared__ C sFourInvH2,sDiffMagic,sDet,sNu,sTauScale;

  const C nu=C(nuIn),tauScale=C(tauScaleIn),supgMagic=C(supgMagicIn);

  for(int ic=(int)blockIdx.x;ic<nc;ic+=(int)gridDim.x){
    const auto&cp=cells[ic];

    if(tid<24){
      const int m=tid/3,d=tid%3;
      sCoeff[m][d]=C(g4_ref_value(cp,m,d,u0,u1,u2,fixed));
    }
    if(tid<12){
      const int a=tid/3,d=tid%3;
      const C g1=C(cp.invJ[d]),g2=C(cp.invJ[3+d]),g3=C(cp.invJ[6+d]);
      sGL[a][d]=(a==0)?-(g1+g2+g3):((a==1)?g1:((a==2)?g2:g3));
    }
    __syncthreads();

    if(tid<16){
      const int a=tid>>2,b=tid&3;
      sGram[a][b]=sGL[a][0]*sGL[b][0]+
                   sGL[a][1]*sGL[b][1]+
                   sGL[a][2]*sGL[b][2];
    }
    if(tid==0){
      sFourInvH2=C(4)/C(cp.h2);
      const C diff=C(4)*nu/C(cp.h2);
      sDiffMagic=supgMagic*diff*diff;
      sDet=C(cp.det);
      sNu=nu;
      sTauScale=tauScale;
    }
    __syncthreads();

    A acc0=A(0),acc1=A(0);

    for(int iq=warp;iq<64;iq+=WARPS){
      C vx=C(0),vy=C(0),vz=C(0);
      if(lane<8){
        const C ph=h7_r2_phi<C>(iq*8+lane);
        vx=ph*sCoeff[lane][0];
        vy=ph*sCoeff[lane][1];
        vz=ph*sCoeff[lane][2];
      }
      for(int off=16;off>0;off>>=1){
        vx+=__shfl_down_sync(0xffffffffu,vx,off);
        vy+=__shfl_down_sync(0xffffffffu,vy,off);
        vz+=__shfl_down_sync(0xffffffffu,vz,off);
      }
      const C adv0=__shfl_sync(0xffffffffu,vx,0);
      const C adv1=__shfl_sync(0xffffffffu,vy,0);
      const C adv2=__shfl_sync(0xffffffffu,vz,0);

      C stream=C(0),strong=C(0);
      if(lane<8){
        C gx,gy,gz,lap;
        if(lane<4){
          gx=sGL[lane][0];gy=sGL[lane][1];gz=sGL[lane][2];
          lap=C(0);
        }else{
          const int bi=lane-4;
          const int j0=h7_r2_bjs[3*bi+0];
          const int j1=h7_r2_bjs[3*bi+1];
          const int j2=h7_r2_bjs[3*bi+2];
          const C c0=h7_r2_gcoef<C>((iq*4+bi)*3+0);
          const C c1=h7_r2_gcoef<C>((iq*4+bi)*3+1);
          const C c2=h7_r2_gcoef<C>((iq*4+bi)*3+2);
          gx=c0*sGL[j0][0]+c1*sGL[j1][0]+c2*sGL[j2][0];
          gy=c0*sGL[j0][1]+c1*sGL[j1][1]+c2*sGL[j2][1];
          gz=c0*sGL[j0][2]+c1*sGL[j1][2]+c2*sGL[j2][2];

          const C l0=h7_r2_phi<C>(iq*8+j0);
          const C l1=h7_r2_phi<C>(iq*8+j1);
          const C l2=h7_r2_phi<C>(iq*8+j2);
          lap=C(54)*(l2*sGram[j0][j1]+
                     l1*sGram[j0][j2]+
                     l0*sGram[j1][j2]);
        }
        stream=adv0*gx+adv1*gy+adv2*gz;
        strong=stream-sNu*lap;
      }

      C w=C(0);
      if(lane==0){
        const C speed2=adv0*adv0+adv1*adv1+adv2*adv2;
        C den=sFourInvH2*speed2+sDiffMagic;
        if(den<C(1e-30))den=C(1e-30);
        w=sTauScale*h7_r2_inv_sqrt<C>(den)*h7_r2_qw<C>(iq)*sDet;
      }
      w=__shfl_sync(0xffffffffu,w,0);

      const int p0=lane,a0=p0>>3,b0=p0&7;
      const C sa0=__shfl_sync(0xffffffffu,stream,a0);
      const C sb0=__shfl_sync(0xffffffffu,strong,b0);
      acc0 += A(w*sa0*sb0);

      const int p1=lane+32,a1=p1>>3,b1=p1&7;
      const C sa1=__shfl_sync(0xffffffffu,stream,a1);
      const C sb1=__shfl_sync(0xffffffffu,strong,b1);
      acc1 += A(w*sa1*sb1);
    }

    sPart[warp][lane]=acc0;
    sPart[warp][lane+32]=acc1;
    __syncthreads();

    if(warp==0){
      A z0=A(0),z1=A(0);
      #pragma unroll
      for(int w=0;w<WARPS;++w){
        z0+=sPart[w][lane];
        z1+=sPart[w][lane+32];
      }

      const int p0=lane,a0=p0>>3,b0=p0&7,r0=cp.ref[a0];
      if(r0>=0){
        const OperatorReal q=OperatorReal(z0);
        if(cp.ref[b0]>=0){
          const unsigned char sl=cp.rowSlot[p0];
          if(sl!=255)atomicAdd(aval+row[r0]+sl,q);
        }else{
          const int fs=-cp.ref[b0]-1;
          atomicAdd(cr0+r0,-StateReal(q)*fixed[3*(std::size_t)fs+0]);
          atomicAdd(cr1+r0,-StateReal(q)*fixed[3*(std::size_t)fs+1]);
          atomicAdd(cr2+r0,-StateReal(q)*fixed[3*(std::size_t)fs+2]);
        }
      }

      const int p1=lane+32,a1=p1>>3,b1=p1&7,r1=cp.ref[a1];
      if(r1>=0){
        const OperatorReal q=OperatorReal(z1);
        if(cp.ref[b1]>=0){
          const unsigned char sl=cp.rowSlot[p1];
          if(sl!=255)atomicAdd(aval+row[r1]+sl,q);
        }else{
          const int fs=-cp.ref[b1]-1;
          atomicAdd(cr0+r1,-StateReal(q)*fixed[3*(std::size_t)fs+0]);
          atomicAdd(cr1+r1,-StateReal(q)*fixed[3*(std::size_t)fs+1]);
          atomicAdd(cr2+r1,-StateReal(q)*fixed[3*(std::size_t)fs+2]);
        }
      }
    }
    __syncthreads();
  }
}
// Persistent warp-per-momentum-row row-L1/relaxation finalizer.
__global__ void h7_finalize_relax_warp_row_kernel(
    int n,const std::int64_t* __restrict__ rp,
    const std::int32_t* __restrict__ diagPos,
    OperatorReal alpha,OperatorReal* __restrict__ av,
    OperatorReal* __restrict__ delta,
    OperatorReal* __restrict__ diag,
    OperatorReal* __restrict__ rau)
{
  const int tid=(int)(blockIdx.x*blockDim.x+threadIdx.x);
  const int lane=tid&31;
  const int warpGlobal=tid>>5;
  const int warpStride=((int)gridDim.x*(int)blockDim.x)>>5;

  for(int i=warpGlobal;i<n;i+=warpStride){
    OperatorReal m=0;
    for(std::int64_t k=rp[i]+lane;k<rp[i+1];k+=32)
      m += fabs(av[k]);

    for(int off=16;off>0;off>>=1)
      m += __shfl_down_sync(0xffffffffu,m,off);

    if(lane==0){
      const OperatorReal de=(OperatorReal(1)/alpha-OperatorReal(1))*m;
      const int dp=diagPos[i];
      delta[i]=de;
      av[dp]+=de;
      diag[i]=av[dp];
      rau[i]=OperatorReal(1)/av[dp];
    }
  }
}

template<class T>
__global__ void h7_diff_kernel(std::size_t n,const T*a,const T*b,T*d)
{
  const std::size_t i=(std::size_t)blockIdx.x*blockDim.x+threadIdx.x;
  if(i<n)d[i]=a[i]-b[i];
}

inline int h7_blocks_for_sm_factor(int smCount,int factor)
{
  return smCount*factor;
}

